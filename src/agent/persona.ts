/**
 * 导师人格：三种「怎么教、怎么说话」的模式。
 *
 * **它不进系统提示词，而是以一条隐藏的 user 消息进入上下文**——这正是工作流的做法
 * （见 learn/workflows 的说明）。这么安排有两个不能让步的理由：
 *
 * 1. **前缀缓存**：系统提示词是整段上下文的最前面。人格写进去，用户每换一次人格，
 *    从第一个 token 起就与上一轮不同，服务端缓存整段作废——而人格恰恰是「一边聊一边换」
 *    的东西。做成中途插进历史的一条消息，换人格只影响它之后的部分，前面的照旧命中缓存。
 * 2. **不重发历史**：人格变了不必把之前的对话重讲一遍，只需在切换到的那一刻补一句
 *    「从现在起按这个人格来」，之后的历史里的人格的指令就留在那儿了。
 *
 * 代价是「什么时候补这一句」要有个准头：一条对话里只补一次（见 needsPersonaAnnounce），
 * 而且被压缩掉之后要能补回来——否则长对话聊到一半，导师会悄悄变回默认语气。
 */

/** 三种人格的 id。存进设置与消息里，改名会让老数据认不出来，所以取语义化的短词 */
export type PersonaId = 'concise' | 'standard' | 'adhd'

export interface Persona {
  id: PersonaId
  /** 列表里的名字：简洁导师 / 标准导师 / ADHD 导师 */
  label: string
  /** 标题后面括号里那个短名 */
  short: string
  /** 一句话的角色定位（副标题） */
  role: string
  /** 三种人格的核心区别，一句话 */
  tagline: string
  /** 进入上下文的那一整段指令（含共同底线，自足：模型看不到别的解释） */
  instruction: string
}

