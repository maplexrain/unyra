/**
 * 「+」菜单与消息定位条的几何 / 时长常量。
 *
 * 这些数字以前长在 AgentPanel 顶上，和一大堆状态混在一起；搬出来单独一处，
 * 改时长或改命中区高度时不必先读两千行。
 */

/** 二级菜单滑动时长，与 index.css 的 .moji-slide-* 对齐（动画播完才卸载旧的那一层） */
export const MENU_SLIDE_MS = 260
/** 菜单退场时长，与 index.css 的 .moji-bloom-up-out 对齐（略长一点，动画播完才卸载） */
export const MENU_EXIT_MS = 170

/**
 * 定位条里两点之间的距离，同时也是**每一项命中区的高度**。
 *
 * 命中区首尾相接、中间不留缝（见下面那条 rail 的写法）：鼠标顺着条子上下走时
 * 不会在两点之间「踩空」，预览浮层也就不会半路消失。视觉上仍然是分开的几道线，
 * 因为线画在伪元素上、只有 3px——剩下的十几像素就是看着分开的那段空白，
 * 而它们照样落在命中区里：「看着分开，摸着连着」。
 * 22 而不是更疏：点数一多，整条子就不该再往下拖那么长。
 */
export const RAIL_PITCH = 22
/** 定位条上下各留的空白：点的命中区不至于贴到列表边缘 */
export const RAIL_PAD = 16
/**
 * 导师栏窄于这个宽度就不显示定位条。
 * 它连同命中区要占掉 20px，窄栏里那点地方该留给消息本身——那才是要读的东西。
 */
export const RAIL_MIN_WIDTH = 600
/*
 * 定位条的横向几何（三处得一起改）：
 *
 *   面板右边 │←12px(right-3)→│ 点 12~18px │←6px→│ 正文右边缘（滚动容器 pr-9 = 36px）
 *
 * 换句话说：轨道离面板右边 12px，最宽的点右边距 12px、左边离正文 6px。
 * 想让点更宽或者离边更远，pr-9 要跟着加，否则那个最宽的点会压到正文上。
 *
 * 纵向不在这一组里：命中区高度就是 RAIL_PITCH（见上），按钮上下相接、不留缝，
 * 所以那条子看着是断续的几道线，摸着却是一整条。
 */

/** 跳过去的那条消息闪多久（与 index.css 的 moji-msg-flash 时长是一对，改一个记得改另一个） */
export const MSG_FLASH_MS = 1100
/** 等「滚动结束」的上限：没有 scrollend（或这次没滚动）时，等这么久就直接闪 */
export const MSG_FLASH_FALLBACK_MS = 700
