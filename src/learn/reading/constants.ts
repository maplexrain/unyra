/** 这个文件负责：阅读记录的口径常量——静默多久停表、心跳与结算间隔、学习日界、热身与「读完」的门槛、明细与日索引的上限。 */

/** 静默多久就停表（不是扣表：停下来就只是不计时，不算「走神」） */
export const IDLE_MS = 60_000
/** 心跳间隔：计时精度与开销的折中 */
export const BEAT_MS = 1_000
/** 结算间隔：攒多久往 store 里写一次（写一次 = 一次 state.json 落盘 + 一次可能的界面刷新） */
export const SETTLE_MS = 30_000
/** 学习日的起点（小时）：凌晨 4 点前算前一天 */
export const DAY_START_HOUR = 4
/** 一节的覆盖比例到多少算「读到了」 */
export const SECTION_REACHED = 0.6
/**
 * 陌生标签页的「热身」时长：今天还没记录过的标签页，要读够这么久、并且**真的动过**，
 * 才开始计入有效阅读（见 warmupDone）。
 *
 * 为什么要有这道门槛：打开一个页签看一眼就走、在知识树里划过去顺手点开一个节点、
 * 或者只是把它当成一个「待会儿看」的占位——这些都会让时长虚高，而虚高的时长会一路
 * 喂给注意力评级、打卡资格与番茄钟建议。20 秒是「一眼扫过」与「坐下来读」之间的分界。
 */
export const WARMUP_MS = 20_000
/**
 * 「不必先交互」的宽限：打开 / 切到这份文档、把文档切回主位之后给这么久。
 *
 * 这三个动作都是**明确的选择**（点了那个页签、点了侧栏那个节点、把文档摆回主位），
 * 不该再要一次滚动才肯计时。反过来，「把窗口拿回前台」（alt-tab、点任务栏、最小化恢复）
 * 不算——那只是窗口回来了，不说明要读，它必须等一次文档区交互。宽限用完还没交互就停表。
 *
 * 20 秒与热身门槛同一个数：打开一份文档到第一次滚动，通常十秒内就发生了。
 */
export const RESUME_GRACE_MS = 20_000
/** 整份文档判「读完」的覆盖线与时长下限 */
export const DOC_DONE_REACH = 0.85
export const DOC_DONE_MS = 60_000

/** 明细日志的上限：超出时丢最旧的（汇总早就把它们算进去了） */
export const MAX_SESSIONS_TOTAL = 400
export const MAX_SESSIONS_PER_NODE = 40
/** 学习日索引保留多少天 */
export const MAX_DAYS = 90
